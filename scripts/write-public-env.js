#!/usr/bin/env node
/**
 * Generates js/env.js for the static site from environment variables.
 *
 * Used on Vercel at build time so the browser receives only:
 *   - SUPABASE_URL
 *   - SUPABASE_ANON_KEY
 *   - USE_LIVE_CATALOG (optional; default false — keeps demo products until cutover)
 *   - USE_STRIPE_CHECKOUT (optional; default false — keeps demo checkout until ready)
 *
 * Never reads or writes:
 *   SUPABASE_SERVICE_ROLE_KEY, STRIPE_SECRET_KEY, STRIPE_WEBHOOK_SECRET,
 *   or any sk_/rk_/whsec_ values.
 * js/env.js stays gitignored; it is produced during `npm run build`.
 */
const fs = require("fs");
const path = require("path");

const outFile = path.join(__dirname, "..", "js", "env.js");

const url = String(
  process.env.SUPABASE_URL ||
    process.env.NEXT_PUBLIC_SUPABASE_URL ||
    process.env.PUBLIC_SUPABASE_URL ||
    ""
).trim();

const anonKey = String(
  process.env.SUPABASE_ANON_KEY ||
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
    process.env.PUBLIC_SUPABASE_ANON_KEY ||
    ""
).trim();

const configured =
  Boolean(url) &&
  Boolean(anonKey) &&
  !url.includes("YOUR_PROJECT_REF") &&
  !anonKey.includes("YOUR_SUPABASE_ANON_KEY");

const finalUrl = configured ? url : "https://YOUR_PROJECT_REF.supabase.co";
const finalAnon = configured ? anonKey : "YOUR_SUPABASE_ANON_KEY";

// Default OFF until migrations 07–08 are applied and import is verified.
const useLiveCatalog =
  String(process.env.USE_LIVE_CATALOG || "").trim().toLowerCase() === "true";

// Public feature flag only — never write Stripe secrets into js/env.js.
// Keep false until /api/create-checkout-session works with keys + webhook.
// Primary name: USE_STRIPE_CHECKOUT (set this in Vercel Production).
const useStripeCheckoutRaw = String(
  process.env.USE_STRIPE_CHECKOUT ||
    process.env.NEXT_PUBLIC_USE_STRIPE_CHECKOUT ||
    process.env.PUBLIC_USE_STRIPE_CHECKOUT ||
    ""
)
  .trim()
  .toLowerCase();
const useStripeCheckout = useStripeCheckoutRaw === "true";

if (!configured) {
  console.warn(
    "[write-public-env] SUPABASE_URL and/or SUPABASE_ANON_KEY are missing."
  );
  console.warn(
    "[write-public-env] Writing placeholders so the storefront can still deploy."
  );
  console.warn(
    "[write-public-env] Add both variables in Vercel → Project Settings → Environment Variables, then redeploy."
  );
} else {
  console.log("[write-public-env] Writing js/env.js with public Supabase URL + anon key.");
}

console.log(
  "[write-public-env] USE_LIVE_CATALOG=" +
    useLiveCatalog +
    " (set env USE_LIVE_CATALOG=true only after migrations 07–08 are applied)."
);
console.log(
  "[write-public-env] USE_STRIPE_CHECKOUT=" +
    useStripeCheckout +
    " (public flag only; Stripe secrets stay server-side)."
);

// Public build stamp so owners can confirm which commit’s static JS is live.
const buildCommit = String(
  process.env.VERCEL_GIT_COMMIT_SHA ||
    process.env.CF_PAGES_COMMIT_SHA ||
    ""
).trim();
const buildStamp = (buildCommit || "local").slice(0, 12);
console.log("[write-public-env] BUILD_COMMIT=" + (buildCommit || "(local)"));

const banner = `/**
 * AUTO-GENERATED by scripts/write-public-env.js - do not edit by hand.
 * Contains only public browser values (URL + anon key + feature flags).
 * Never service-role or Stripe secret/webhook keys.
 */
`;

const body =
  banner +
  "window.__SR_ENV__ = {\n" +
  `  SUPABASE_URL: ${JSON.stringify(finalUrl)},\n` +
  `  SUPABASE_ANON_KEY: ${JSON.stringify(finalAnon)},\n` +
  `  USE_LIVE_CATALOG: ${JSON.stringify(useLiveCatalog)},\n` +
  `  USE_STRIPE_CHECKOUT: ${JSON.stringify(useStripeCheckout)},\n` +
  `  BUILD_COMMIT: ${JSON.stringify(buildCommit || null)},\n` +
  "};\n";

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body, "utf8");
console.log(`[write-public-env] Wrote ${outFile}`);

// Cache-bust storefront script URLs in the deploy artifact only (Vercel build tree).
const indexPath = path.join(__dirname, "..", "index.html");
if (fs.existsSync(indexPath)) {
  var html = fs.readFileSync(indexPath, "utf8");
  var next = html
    .replace(
      /href="\/styles\.css(?:\?v=[^"]*)?"/g,
      'href="/styles.css?v=' + buildStamp + '"'
    )
    .replace(
      /src="\/js\/env\.js(?:\?v=[^"]*)?"/g,
      'src="/js/env.js?v=' + buildStamp + '"'
    )
    .replace(
      /src="\/js\/appearance\.js(?:\?v=[^"]*)?"/g,
      'src="/js/appearance.js?v=' + buildStamp + '"'
    )
    .replace(
      /src="\/app\.js(?:\?v=[^"]*)?"/g,
      'src="/app.js?v=' + buildStamp + '"'
    );
  if (next !== html) {
    fs.writeFileSync(indexPath, next, "utf8");
    console.log(
      "[write-public-env] Stamped index.html script URLs with ?v=" + buildStamp
    );
  }
}
